--  Schema version : 013
--  Introduced in  : Core 2.0.0 (migration 012 → 013, "Re-platform order tables")
--  Summary        : Orders, provider attempts, order timeline, idempotency
--                   keys and the append-only balance ledger.
--
--  Installations upgrading from 1.x on MySQL import their legacy orders with
--  the one-off importer (`orvexctl import legacy-mysql`) after this migration;
--  orders.number is GENERATED BY DEFAULT so legacy order numbers are preserved.
-- =============================================================================

CREATE TABLE orders (
  id                          uuid          PRIMARY KEY DEFAULT gen_random_uuid(),
  number                      bigint        GENERATED BY DEFAULT AS IDENTITY (START WITH 10001) UNIQUE,
  service_id                  uuid          NOT NULL REFERENCES services(id) ON DELETE RESTRICT,
  reseller_id                 uuid          REFERENCES resellers(id) ON DELETE RESTRICT,
  channel                     text          NOT NULL CHECK (channel IN ('api', 'website', 'admin')),
  environment                 text          NOT NULL DEFAULT 'live' CHECK (environment IN ('live', 'test')),
  provider_id                 uuid          REFERENCES providers(id) ON DELETE RESTRICT,
  status                      text          NOT NULL DEFAULT 'created'
                                            CHECK (status IN ('created', 'processing', 'pending', 'success', 'failed', 'refunded', 'cancelled')),
  routing_strategy            text          NOT NULL
                                            CHECK (routing_strategy IN ('priority', 'lowest_cost', 'fastest', 'health_weighted', 'round_robin')),
  price                       numeric(12,4) NOT NULL CHECK (price >= 0),
  cost                        numeric(12,4) NOT NULL DEFAULT 0 CHECK (cost >= 0),
  currency                    char(3)       NOT NULL DEFAULT 'USD' CHECK (currency ~ '^[A-Z]{3}$'),
  input                       jsonb         NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(input) = 'object'),
  input_sensitive_ciphertext  bytea,
  input_sensitive_nonce       bytea         CHECK (input_sensitive_nonce IS NULL OR octet_length(input_sensitive_nonce) = 12),
  input_sensitive_key_id      text,
  result                      jsonb         CHECK (result IS NULL OR jsonb_typeof(result) = 'object'),
  error_code                  text          CHECK (error_code ~ '^[a-z_]+$'),
  error_message               text,
  client_reference            text          CHECK (length(client_reference) <= 128),
  request_id                  text          NOT NULL,
  api_key_id                  uuid          REFERENCES api_keys(id) ON DELETE SET NULL,
  created_by                  uuid          REFERENCES users(id) ON DELETE SET NULL,
  retry_of                    uuid          REFERENCES orders(id) ON DELETE SET NULL,
  created_at                  timestamptz   NOT NULL DEFAULT now(),
  updated_at                  timestamptz   NOT NULL DEFAULT now(),
  completed_at                timestamptz,
  sensitive_purged_at         timestamptz,
  CONSTRAINT orders_terminal_has_completed_at
    CHECK ((status IN ('success', 'failed', 'refunded', 'cancelled')) = (completed_at IS NOT NULL)),
  CONSTRAINT orders_error_pair
    CHECK ((error_code IS NULL) = (error_message IS NULL)),
  CONSTRAINT orders_success_has_result
    CHECK (status NOT IN ('success', 'refunded') OR result IS NOT NULL),
  CONSTRAINT orders_sensitive_complete
    CHECK (num_nulls(input_sensitive_ciphertext, input_sensitive_nonce, input_sensitive_key_id) IN (0, 3))
);

-- orders_created_at_idx is superseded by (created_at DESC, status) in 018.
CREATE INDEX orders_created_at_idx         ON orders (created_at);
CREATE INDEX orders_in_flight_idx          ON orders (status, updated_at) WHERE status IN ('created', 'processing', 'pending');
CREATE INDEX orders_reseller_created_idx   ON orders (reseller_id, created_at DESC) WHERE reseller_id IS NOT NULL;
CREATE INDEX orders_service_created_idx    ON orders (service_id, created_at DESC);
CREATE INDEX orders_provider_created_idx   ON orders (provider_id, created_at DESC) WHERE provider_id IS NOT NULL;
CREATE INDEX orders_request_id_idx         ON orders (request_id);
CREATE INDEX orders_client_reference_idx   ON orders (reseller_id, client_reference) WHERE client_reference IS NOT NULL;

COMMENT ON TABLE orders IS
  'Orders from the Reseller API, the public website or the admin. API id = ''ord_'' || number (e.g. ord_10482); displayed as #10482.';
COMMENT ON COLUMN orders.status IS
  'created → processing → (pending) → success | failed; success → refunded; created|pending → cancelled. pending also covers orders held for manual review (error_code = held_for_review).';
COMMENT ON COLUMN orders.environment IS
  'test = created with a orx_test_ key: routed to provider sandbox connections (provider_connections.environment = test), never charged to the ledger, excluded from reports.';
COMMENT ON COLUMN orders.routing_strategy IS
  'Strategy in effect for this order after routing rules (snapshot for auditability).';
COMMENT ON COLUMN orders.price IS
  'Price charged, frozen at order time from the reseller''s pricing group (or the public price).';
COMMENT ON COLUMN orders.cost IS
  'Provider cost of the successful attempt; 0 for failed orders.';
COMMENT ON COLUMN orders.input IS
  'Order input with sensitive fields masked (e.g. {"phone_number": "+44 ••• ••• 123"} for SVC-1023 Carrier Lookup). Never contains a sensitive value in clear.';
COMMENT ON COLUMN orders.input_sensitive_ciphertext IS
  'AES-256-GCM encrypted JSON of the sensitive fields, needed to submit to providers and to retry. Purged (set to NULL, sensitive_purged_at set) after the data-retention window.';
COMMENT ON COLUMN orders.result IS
  '{"summary": "…", "data": {…}} as normalised by the adapter, e.g. {"summary": "NCK 48213907", "data": {"nck": "48213907"}} or {"summary": "CLEAN — not on the GSMA blacklist", "data": {"blacklisted": false}}.';
COMMENT ON COLUMN orders.request_id IS
  'X-Request-Id of the request that created the order (req_…), correlating API logs, provider logs and webhooks.';

CREATE TRIGGER orders_set_updated_at BEFORE UPDATE ON orders
  FOR EACH ROW EXECUTE FUNCTION orvex_set_updated_at();

-- -----------------------------------------------------------------------------
-- order_attempts — each submission to a provider (primary + fallbacks).
-- -----------------------------------------------------------------------------
CREATE TABLE order_attempts (
  id            uuid          PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id      uuid          NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  attempt_no    smallint      NOT NULL CHECK (attempt_no >= 1),
  provider_id   uuid          NOT NULL REFERENCES providers(id) ON DELETE RESTRICT,
  mapping_id    uuid          REFERENCES service_mappings(id) ON DELETE SET NULL,
  role          text          NOT NULL DEFAULT 'primary' CHECK (role IN ('primary', 'fallback', 'emergency')),
  started_at    timestamptz   NOT NULL DEFAULT now(),
  ended_at      timestamptz,
  outcome       text          NOT NULL DEFAULT 'in_flight'
                              CHECK (outcome IN ('success', 'timeout', 'rejected', 'error', 'in_flight')),
  latency_ms    integer       NOT NULL DEFAULT 0 CHECK (latency_ms >= 0),
  http_status   smallint      CHECK (http_status BETWEEN 100 AND 599),
  message       text          NOT NULL DEFAULT '',
  external_ref  text,
  cost          numeric(12,4) CHECK (cost >= 0),
  CONSTRAINT order_attempts_sequence_unique UNIQUE (order_id, attempt_no),
  CONSTRAINT order_attempts_in_flight_open  CHECK ((outcome = 'in_flight') = (ended_at IS NULL)),
  CONSTRAINT order_attempts_time_window     CHECK (ended_at IS NULL OR ended_at >= started_at)
);

CREATE UNIQUE INDEX order_attempts_external_ref_key ON order_attempts (provider_id, external_ref) WHERE external_ref IS NOT NULL;
CREATE INDEX order_attempts_provider_started_idx ON order_attempts (provider_id, started_at DESC);

COMMENT ON TABLE order_attempts IS
  'OrderAttempt. A timeout, error or rejection is followed by the next provider in the chain (fallback); rejected (definitive) stops the chain.';
COMMENT ON COLUMN order_attempts.external_ref IS
  'Provider reference returned by ProviderAdapter.submitOrder; unique per provider so inbound provider webhooks resolve to exactly one attempt.';

-- -----------------------------------------------------------------------------
-- order_events — order timeline (append-only).
-- -----------------------------------------------------------------------------
CREATE TABLE order_events (
  id           bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  order_id     uuid        NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  type         text        NOT NULL
               CHECK (type IN ('created', 'validated', 'charged', 'routed', 'submitted', 'accepted', 'provider_timeout',
                               'provider_error', 'retry', 'processing', 'completed', 'failed', 'refunded', 'webhook_sent')),
  at           timestamptz NOT NULL DEFAULT now(),
  title        text        NOT NULL,
  detail       text,
  provider_id  uuid        REFERENCES providers(id) ON DELETE RESTRICT,
  tone         text        NOT NULL DEFAULT 'neutral' CHECK (tone IN ('neutral', 'success', 'warning', 'danger', 'accent')),
  data         jsonb       CHECK (data IS NULL OR jsonb_typeof(data) = 'object')
);

CREATE INDEX order_events_order_at_idx ON order_events (order_id, at);

-- Events are immutable. Deletion is only possible through the order (retention).
CREATE TRIGGER order_events_immutable BEFORE UPDATE ON order_events
  FOR EACH ROW EXECUTE FUNCTION orvex_forbid_mutation();

COMMENT ON TABLE order_events IS
  'OrderEvent timeline written by the pipeline as it happens (routing decisions and applied rules are recorded in data).';

-- -----------------------------------------------------------------------------
-- idempotency_keys — Idempotency-Key handling for POST /api/v1/orders.
-- -----------------------------------------------------------------------------
CREATE TABLE idempotency_keys (
  id               bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  reseller_id      uuid        REFERENCES resellers(id) ON DELETE CASCADE,
  api_key_id       uuid        NOT NULL REFERENCES api_keys(id) ON DELETE CASCADE,
  key              text        NOT NULL CHECK (length(key) BETWEEN 1 AND 255),
  request_method   text        NOT NULL,
  request_path     text        NOT NULL,
  request_hash     bytea       NOT NULL CHECK (octet_length(request_hash) = 32),
  response_status  smallint,
  response_body    jsonb,
  order_id         uuid        REFERENCES orders(id) ON DELETE SET NULL,
  locked_until     timestamptz,
  created_at       timestamptz NOT NULL DEFAULT now(),
  expires_at       timestamptz NOT NULL
);

CREATE UNIQUE INDEX idempotency_keys_scope_key ON idempotency_keys ((COALESCE(reseller_id, api_key_id)), key);
CREATE INDEX idempotency_keys_expiry_idx ON idempotency_keys (expires_at);

COMMENT ON TABLE idempotency_keys IS
  'Scoped per reseller (or per internal key). Same key + same request hash within settings.api.idempotencyWindowHours (24 h) replays the stored response; same key + different body returns 409 idempotency_conflict; a concurrent duplicate waits on locked_until.';

-- -----------------------------------------------------------------------------
-- transactions — append-only balance ledger.
-- -----------------------------------------------------------------------------
CREATE TABLE transactions (
  id                  uuid          PRIMARY KEY DEFAULT gen_random_uuid(),
  at                  timestamptz   NOT NULL DEFAULT now(),
  type                text          NOT NULL
                                    CHECK (type IN ('order_charge', 'top_up', 'refund', 'adjustment', 'provider_settlement')),
  reseller_id         uuid          REFERENCES resellers(id) ON DELETE RESTRICT,
  provider_id         uuid          REFERENCES providers(id) ON DELETE RESTRICT,
  order_id            uuid          REFERENCES orders(id) ON DELETE RESTRICT,
  amount              numeric(12,4) NOT NULL CHECK (amount <> 0),
  currency            char(3)       NOT NULL DEFAULT 'USD' CHECK (currency ~ '^[A-Z]{3}$'),
  balance_after       numeric(12,4),
  description         text          NOT NULL DEFAULT '',
  method              text          NOT NULL
                                    CHECK (method IN ('balance', 'card', 'bank_transfer', 'manual', 'provider_wallet')),
  status              text          NOT NULL DEFAULT 'completed' CHECK (status IN ('completed', 'pending', 'failed')),
  external_reference  text,
  created_by          uuid          REFERENCES users(id),
  settled_at          timestamptz,
  CONSTRAINT transactions_exactly_one_account
    CHECK (num_nonnulls(reseller_id, provider_id) = 1),
  CONSTRAINT transactions_sign_and_links_by_type CHECK (
       (type = 'order_charge'        AND amount < 0 AND order_id IS NOT NULL AND reseller_id IS NOT NULL)
    OR (type = 'refund'              AND amount > 0 AND order_id IS NOT NULL AND reseller_id IS NOT NULL)
    OR (type = 'top_up'              AND amount > 0 AND reseller_id IS NOT NULL)
    OR (type = 'provider_settlement' AND amount < 0 AND provider_id IS NOT NULL)
    OR (type = 'adjustment')
  )
);

-- An order can be charged once and refunded/released once — enforced by the database.
CREATE UNIQUE INDEX transactions_one_charge_per_order ON transactions (order_id)
  WHERE type = 'order_charge' AND status <> 'failed';
CREATE UNIQUE INDEX transactions_one_refund_per_order ON transactions (order_id)
  WHERE type = 'refund' AND status <> 'failed';
CREATE INDEX transactions_at_idx           ON transactions (at DESC);
CREATE INDEX transactions_reseller_at_idx  ON transactions (reseller_id, at DESC) WHERE reseller_id IS NOT NULL;
CREATE INDEX transactions_provider_at_idx  ON transactions (provider_id, at DESC) WHERE provider_id IS NOT NULL;
CREATE INDEX transactions_pending_idx      ON transactions (at) WHERE status = 'pending';

COMMENT ON TABLE transactions IS
  'Ledger (Transaction). Amounts are signed from the account''s point of view: reseller account (order_charge < 0, top_up/refund > 0) or the installation''s provider wallet (provider_settlement < 0). Entries are never edited or deleted; corrections are new adjustment entries.';
COMMENT ON COLUMN transactions.balance_after IS
  'Reseller balance immediately after this entry (completed reseller entries).';
COMMENT ON COLUMN transactions.method IS
  'balance = paid from prepaid balance; card / bank_transfer = top-up channels (payment provider references only, never card data); provider_wallet = prepaid wallet at a provider.';

CREATE OR REPLACE FUNCTION orvex_transactions_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'transactions is an append-only ledger; post a reversing adjustment instead'
      USING ERRCODE = 'restrict_violation';
  END IF;
  -- Only a pending entry may change, and only its settlement fields
  -- (status, balance_after, settled_at, external_reference, description).
  IF OLD.status <> 'pending'
     OR NEW.type        IS DISTINCT FROM OLD.type
     OR NEW.amount      IS DISTINCT FROM OLD.amount
     OR NEW.currency    IS DISTINCT FROM OLD.currency
     OR NEW.reseller_id IS DISTINCT FROM OLD.reseller_id
     OR NEW.provider_id IS DISTINCT FROM OLD.provider_id
     OR NEW.order_id    IS DISTINCT FROM OLD.order_id
     OR NEW.at          IS DISTINCT FROM OLD.at THEN
    RAISE EXCEPTION 'ledger entry % is immutable', OLD.id
      USING ERRCODE = 'restrict_violation';
  END IF;
  RETURN NEW;
END
$$;

CREATE TRIGGER transactions_guard BEFORE UPDATE OR DELETE ON transactions
  FOR EACH ROW EXECUTE FUNCTION orvex_transactions_guard();
