--  Schema version : 008
--  Introduced in  : Core 1.x (consolidated)
--  Summary        : The customer's resellers (their B2B clients using the
--                   Reseller API), balances, limits and service access.
--  Note           : resellers.pricing_group_id is added in 016 (Core 2.3.0).
-- =============================================================================

CREATE TABLE resellers (
  id                 uuid          PRIMARY KEY DEFAULT gen_random_uuid(),
  number             integer       GENERATED BY DEFAULT AS IDENTITY (START WITH 100) UNIQUE,
  name               text          NOT NULL CHECK (length(name) BETWEEN 1 AND 160),
  contact_name       text          NOT NULL DEFAULT '',
  email              text          NOT NULL CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  country            char(2)       NOT NULL CHECK (country ~ '^[A-Z]{2}$'),
  website            text          NOT NULL DEFAULT '',
  status             text          NOT NULL DEFAULT 'pending' CHECK (status IN ('active', 'suspended', 'pending')),
  balance            numeric(12,4) NOT NULL DEFAULT 0,
  credit_limit       numeric(12,4) NOT NULL DEFAULT 0 CHECK (credit_limit >= 0),
  rate_per_minute    integer       NOT NULL DEFAULT 120 CHECK (rate_per_minute BETWEEN 1 AND 100000),
  daily_orders       integer       NOT NULL DEFAULT 500 CHECK (daily_orders >= 0),
  max_concurrent     integer       NOT NULL DEFAULT 10 CHECK (max_concurrent >= 1),
  restrict_services  boolean       NOT NULL DEFAULT false,
  webhook_url        text          CHECK (webhook_url ~ '^https://'),
  notes              text          NOT NULL DEFAULT '',
  last_active_at     timestamptz,
  created_at         timestamptz   NOT NULL DEFAULT now(),
  updated_at         timestamptz   NOT NULL DEFAULT now(),
  CONSTRAINT resellers_balance_within_credit CHECK (balance + credit_limit >= 0)
);

CREATE INDEX resellers_status_idx ON resellers (status);
CREATE INDEX resellers_email_idx ON resellers (lower(email));

COMMENT ON TABLE resellers IS
  'Resellers of this installation. API id = ''rsl_'' || number (e.g. rsl_482). Never deleted once they have ledger entries.';
COMMENT ON COLUMN resellers.balance IS
  'Running prepaid balance. Changed ONLY in the same transaction as a transactions (ledger) insert, under SELECT … FOR UPDATE; must equal the sum of completed ledger entries (verified by the nightly reconciliation job).';
COMMENT ON CONSTRAINT resellers_balance_within_credit ON resellers IS
  'Hard backstop against overdraft: an order charge that would exceed the credit limit fails at the database level even if application checks were bypassed.';
COMMENT ON COLUMN resellers.restrict_services IS
  'false = all API-visible services allowed (allowedServiceIds = ''all''); true = only services listed in reseller_services.';
COMMENT ON COLUMN resellers.webhook_url IS
  'Primary callback URL shown on the reseller profile. Deliveries are driven by rows in webhooks (014).';

CREATE TRIGGER resellers_set_updated_at BEFORE UPDATE ON resellers
  FOR EACH ROW EXECUTE FUNCTION orvex_set_updated_at();

CREATE TABLE reseller_services (
  reseller_id  uuid NOT NULL REFERENCES resellers(id) ON DELETE CASCADE,
  service_id   uuid NOT NULL REFERENCES services(id) ON DELETE CASCADE,
  PRIMARY KEY (reseller_id, service_id)
);

COMMENT ON TABLE reseller_services IS
  'Allow-list of services for resellers with restrict_services = true.';
